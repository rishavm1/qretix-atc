"""
Phase 8 — Evidence Card Generator
===================================
Generates one markdown evidence card per top-ranked ATC candidate gene.

Each card contains:
  - Gene metadata (symbol, name, Ensembl ID, UniProt)
  - Label stage + evidence sources
  - Biology score decomposition
  - Therapeutic score decomposition
  - Novelty sub-scores (5 independent)
  - Supporting evidence summary
  - Computational hypothesis disclaimer

Output: evidence_cards/{GENE}.md per top candidate
"""
from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

log = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parents[2]
FEATURES_PATH = ROOT / "features" / "feature_table.parquet"
LABELS_PATH   = ROOT / "labels" / "labels.parquet"
NOVELTY_PATH  = ROOT / "features" / "novelty_scores.parquet"
QRETIX_PATH   = ROOT / "models" / "qretix_ranker" / "qretix_scores.parquet"
GU_PATH       = ROOT / "data" / "processed" / "gene_universe.parquet"
OUT_DIR       = ROOT / "evidence_cards"

TOP_N = 50   # generate cards for top 50 ranked genes


def _fmt(val, decimals=3) -> str:
    if val is None or (isinstance(val, float) and pd.isna(val)):
        return "N/A"
    if isinstance(val, float):
        return f"{val:.{decimals}f}"
    return str(val)


def generate_card(
    symbol: str,
    gu_row: pd.Series,
    label_row: pd.Series,
    feat_row: pd.Series,
    nov_row: pd.Series,
    qretix_row: pd.Series,
) -> str:
    name = gu_row.get("name", "") or ""
    ensembl = gu_row.get("ensembl_gene_id", "") or ""
    uniprot = gu_row.get("uniprot_id", "") or ""
    stage = int(label_row.get("stage", 0))
    evidence_sources = label_row.get("evidence_sources", "") or ""
    earliest_date = label_row.get("earliest_evidence_date", "") or ""

    stage_labels = {
        0: "Stage 0 — No meaningful ATC evidence",
        1: "Stage 1 — Preclinical evidence (in vitro/in vivo ATC)",
        2: "Stage 2 — Experimental therapeutic evidence (perturbation → phenotype)",
        3: "Stage 3 — Clinical investigation (active ATC trial)",
        4: "Stage 4 — Validated / approved drug target in ATC",
    }

    lines = [
        f"# Evidence Card: {symbol}",
        "",
        "> ⚠️ **Computational hypothesis** — This card is generated by an automated",
        "> ranking pipeline. All findings require experimental validation before",
        "> any clinical or therapeutic conclusions are drawn.",
        "",
        "## Gene Metadata",
        "",
        f"| Field | Value |",
        f"|-------|-------|",
        f"| Symbol | {symbol} |",
        f"| Name | {name} |",
        f"| Ensembl ID | {ensembl} |",
        f"| UniProt | {uniprot} |",
        f"| QRETIX Score | {_fmt(qretix_row.get('qretix_score', None))} |",
        "",
        "## ATC Evidence Stage",
        "",
        f"**{stage_labels.get(stage, f'Stage {stage}')}**",
        "",
        f"- Earliest evidence date: {earliest_date or 'N/A'}",
        f"- Evidence sources: {evidence_sources or 'None'}",
        "",
        "## Supporting Evidence",
        "",
        "### Biology Score Components",
        "",
        "| Feature | Value |",
        "|---------|-------|",
        f"| scRNA specificity (malignant) | {_fmt(feat_row.get('scrna_specificity'))} |",
        f"| Bulk ATC vs PDTC fold-change | {_fmt(feat_row.get('bulk_atc_vs_pdtc_fc'))} |",
        f"| DepMap mean Chronos score | {_fmt(feat_row.get('dep_mean_chronos'))} |",
        f"| DepMap essential fraction | {_fmt(feat_row.get('dep_essential_frac'))} |",
        f"| Mutation frequency (ATC) | {_fmt(feat_row.get('mut_freq'))} |",
        f"| Any genetic event freq | {_fmt(feat_row.get('any_genetic_event'))} |",
        f"| STRING PPI degree | {_fmt(feat_row.get('string_degree'), 0)} |",
        f"| Reactome pathway count | {_fmt(feat_row.get('reactome_pathway_count'), 0)} |",
        f"| Driver proximity (hops) | {_fmt(feat_row.get('ppi_driver_proximity'), 1)} |",
        "",
        "### Therapeutic Score Components",
        "",
        "| Feature | Value |",
        "|---------|-------|",
        f"| OT ATC association score | {_fmt(feat_row.get('ot_atc_score'))} |",
        f"| Druggability tier | {feat_row.get('ot_druggability_tier', 'N/A')} |",
        f"| Approved SM drug (OT) | {_fmt(feat_row.get('ot_sm_approved'), 0)} |",
        f"| Approved antibody (OT) | {_fmt(feat_row.get('ot_ab_approved'), 0)} |",
        f"| ChEMBL modulator count | {_fmt(feat_row.get('chembl_modulator_count'), 0)} |",
        f"| ChEMBL approved count | {_fmt(feat_row.get('chembl_approved_count'), 0)} |",
        f"| UniProt has structure | {_fmt(feat_row.get('uniprot_has_structure'), 0)} |",
        f"| UniProt domain count | {_fmt(feat_row.get('uniprot_domain_count'), 0)} |",
        "",
        "### Novelty Sub-scores (5 independent)",
        "",
        "| Sub-score | Value | Interpretation |",
        "|-----------|-------|----------------|",
        f"| Disease novelty | {_fmt(nov_row.get('disease_novelty'))} | 1=most novel, 0=well-studied in ATC |",
        f"| Target novelty | {_fmt(nov_row.get('target_novelty'))} | 1=novel target, 0=established target |",
        f"| Mechanistic novelty | {_fmt(nov_row.get('mechanistic_novelty'))} | 1=mechanism unknown, 0=well-described |",
        f"| Combination novelty | {_fmt(nov_row.get('combination_novelty'))} | 1=novel pathway combo, 0=known combo |",
        f"| Research saturation | {_fmt(nov_row.get('research_saturation'))} | 1=growing field, 0=saturated |",
        "",
        "### Literature Evidence",
        "",
        f"| Feature | Value |",
        f"|---------|-------|",
        f"| ATC PubMed mentions | {_fmt(feat_row.get('lit_atc_mentions'), 0)} |",
        f"| Thyroid PubMed mentions | {_fmt(feat_row.get('lit_thyroid_mentions'), 0)} |",
        f"| ATC/thyroid ratio | {_fmt(feat_row.get('lit_atc_ratio'))} |",
        f"| Recency score (post-2019) | {_fmt(feat_row.get('lit_recency_score'))} |",
        "",
        "### Cross-modality Evidence",
        "",
        f"| Modality | Supported |",
        f"|----------|-----------|",
        f"| Genomics (mutation/CNA) | {'Yes' if feat_row.get('ev_genomics_flag', 0) else 'No'} |",
        f"| Bulk RNA (ATC vs PDTC) | {'Yes' if feat_row.get('ev_bulk_rna_flag', 0) else 'No'} |",
        f"| scRNA-seq (malignant) | {'Yes' if feat_row.get('ev_scrna_flag', 0) else 'No'} |",
        f"| DepMap dependency | {'Yes' if feat_row.get('ev_depmap_flag', 0) else 'No'} |",
        f"| Literature (≥2 papers) | {'Yes' if feat_row.get('ev_literature_flag', 0) else 'No'} |",
        f"| **Total modalities** | **{int(feat_row.get('ev_n_modalities', 0))} / 5** |",
        "",
        "---",
        "_Generated by QRETIX-ATC v0.1 evidence card pipeline._",
        "_All scores are computational predictions. Experimental validation required._",
    ]
    return "\n".join(lines)


def run(top_n: int = TOP_N):
    OUT_DIR.mkdir(exist_ok=True)

    # Load all data
    log.info("Loading data for evidence card generation...")
    gu = pd.read_parquet(GU_PATH).set_index("hgnc_symbol")
    lb = pd.read_parquet(LABELS_PATH)
    ft = pd.read_parquet(FEATURES_PATH)
    nov = pd.read_parquet(NOVELTY_PATH)

    # Get top genes from QRETIX scores or fall back to RF scores
    if QRETIX_PATH.exists():
        qretix = pd.read_parquet(QRETIX_PATH)
        top_genes = qretix.head(top_n).index.tolist()
    else:
        # Fallback: rank by stage + OT score
        top_genes = lb[lb["stage"] >= 2].index.tolist()[:top_n]
        qretix = pd.DataFrame(index=top_genes)

    log.info("Generating evidence cards for %d top genes...", len(top_genes))
    generated = 0
    for sym in top_genes:
        try:
            gu_row  = gu.loc[sym] if sym in gu.index else pd.Series()
            lb_row  = lb.loc[sym] if sym in lb.index else pd.Series()
            ft_row  = ft.loc[sym] if sym in ft.index else pd.Series()
            nov_row = nov.loc[sym] if sym in nov.index else pd.Series()
            qr_row  = qretix.loc[sym] if sym in qretix.index else pd.Series()

            card = generate_card(sym, gu_row, lb_row, ft_row, nov_row, qr_row)
            out_path = OUT_DIR / f"{sym}.md"
            out_path.write_text(card, encoding="utf-8")
            generated += 1
        except Exception as e:
            log.warning("Failed to generate card for %s: %s", sym, e)

    log.info("Generated %d evidence cards → %s", generated, OUT_DIR)
    return generated


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO,
                        format="%(asctime)s [%(levelname)s] %(message)s")
    run()
